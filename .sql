  CREATE OR REPLACE EDITIONABLE FUNCTION "ETECHSHOPCONN"."FN_LOGIN_USUARIO" (
  p_correo IN VARCHAR2,
  p_hash_out OUT VARCHAR2
) RETURN NUMBER
AS
  v_id       NUMBER;
  v_hash     VARCHAR2(255);
  v_intentos NUMBER;
  v_blk      CHAR(1);
