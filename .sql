  p_id IN NUMBER
) AS
  v_intentos NUMBER;
BEGIN
  SELECT intentos INTO v_intentos
  FROM usuarios
  WHERE id = p_id
  FOR UPDATE;

  v_intentos := NVL(v_intentos,0) + 1;

  IF v_intentos >= 3 THEN
      UPDATE usuarios
      SET intentos = v_intentos,
          bloqueado = 'S'
      WHERE id = p_id;
  ELSE
      UPDATE usuarios
      SET intentos = v_intentos
      WHERE id = p_id;
  END IF;

  COMMIT;
END;

