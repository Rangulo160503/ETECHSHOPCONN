  FUNCTION F_TOTAL_USUARIO(p_id_usuario IN NUMBER) RETURN NUMBER IS
    v_total NUMBER := 0;
    CURSOR c_compras IS
      SELECT total
      FROM compras
      WHERE id_usuario = p_id_usuario;
  BEGIN
    FOR r IN c_compras LOOP
      v_total := v_total + r.total;
    END LOOP;
    RETURN v_total;

  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      RETURN 0;
    WHEN OTHERS THEN
      RAISE_APPLICATION_ERROR(-20002, 'Error calculando total: ' || SQLERRM);
  END F_TOTAL_USUARIO;

